"""Generate xml/Custom_1121_Denon.xml (the Denon receiver settings page) and
xml/Includes_Denon.xml, laid out like the LG TV page (tools/gen_lgtv.py).
Values come from service.denonavr's Denon.* properties and its settings.

    python3 tools/gen_denon.py
"""

from __future__ import annotations

from pathlib import Path

from gen_lgtv import build_page

OUT = Path(__file__).resolve().parent.parent / "xml" / "Custom_1121_Denon.xml"
INCLUDES = OUT.with_name("Includes_Denon.xml")
ADDON = "service.denonavr"
P = "Window(Home).Property"
CONNECTED = f"String.IsEqual({P}(Denon.Connected),true)"
ON = f"{CONNECTED} + String.IsEqual({P}(Denon.Power),true)"
# The add-on publishes its settings as properties: $INFO splits Addon.SettingStr(id,setting) at the comma.
HOST = "$INFO[Window(Home).Property(Denon.Host)]"


def s(n: int) -> str:
    return f"$LOCALIZE[{n}]"


def run(*args: str) -> str:
    return f"RunScript({ADDON},{','.join(args)})"


# Rows as in gen_lgtv.py: ("button", id, label, onclick, label2, enable, help),
# ("radio", id, label, selected, [(condition, onclick)], enable, help),
# ("header", id, label), ("note", id, label, visible).
CATEGORIES = [
    ("receiver", s(31954), [
        ("button", 100, s(31911), run("osd"), "$VAR[DenonStatusText]", CONNECTED, s(31968)),
        ("radio", 101, s(31918), f"String.IsEqual({P}(Denon.Power),true)", [("", run("power", "toggle"))],
         CONNECTED, s(31966)),
        ("button", 102, s(31902), run("osd"), f"$INFO[{P}(Denon.InputName)]", ON, s(31968)),
        ("button", 103, s(31957), run("osd"), "$VAR[DenonSignalText]", ON, s(31969)),
        ("button", 104, s(31958), run("osd"), f"$INFO[{P}(Denon.SoundMode)]", ON, s(31969)),
    ]),
    ("volume", s(31905), [
        ("button", 200, s(31905), run("osd"), "$VAR[DenonVolumeText]", ON, s(31968)),
        ("radio", 201, s(31906), f"String.IsEqual({P}(Denon.Mute),true)", [("", run("mute", "toggle"))], ON, ""),
        ("button", 202, s(31959), run("setting", "volume_step"), "$VAR[DenonVolumeStep]", "", s(31964)),
        ("button", 203, s(31960), run("setting", "max_volume"), "$VAR[DenonMaxVolume]", "", s(31965)),
        ("header", 290, s(31961)),
        ("radio", 204, "$ADDON[service.webostv 32635]", "Addon.SettingBool(service.webostv,bridge_volume_receiver)",
         [("", "RunScript(service.webostv,setting,bridge_volume_receiver)")],
         "$EXP[setup_lg] + Addon.SettingBool(service.webostv,remote_bridge)", "$ADDON[service.webostv 32685]"),
    ]),
    ("connection", s(31910), [
        ("button", 300, s(31955), run("find_receiver"), HOST, "", s(31962)),
        ("button", 301, s(31956), run("setting", "host"), HOST, "", s(31963)),
        ("button", 302, s(31914), f"Addon.OpenSettings({ADDON})", "", "", ""),
    ]),
]


def build() -> str:
    return build_page(
        window_id=1121, category_prop="denon_category", categories=CATEGORIES, help_var="DenonHelp",
        icon="icons/settings/receiver.png", model_label=f"$INFO[{P}(Denon.Model),Denon ,]",
        status_label="$VAR[DenonConnectionText]", breadcrumb="$LOCALIZE[5] / $LOCALIZE[31951]",
        comment="Denon receiver settings page (Settings > Denon receiver). Layout\n"
                "     follows the LG TV page; values come from service.denonavr.",
        generator="tools/gen_denon.py")


def build_includes() -> str:
    helps = [(r[1], r[-1]) for _c, _l, rows in CATEGORIES for r in rows if r[0] in ("button", "radio") and r[-1]]
    help_var = "\n".join(f'\t\t<value condition="Control.HasFocus({cid})">{text}</value>' for cid, text in helps)
    steps = "\n".join(
        f'\t\t<value condition="Integer.IsEqual(Addon.SettingInt({ADDON},volume_step),{i})">{label}</value>'
        for i, label in enumerate(("0.5 dB", "1 dB", "2 dB")))
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<!-- GENERATED by tools/gen_denon.py. Variables for Custom_1121_Denon.xml and the
     receiver volume ring (Custom_1122_ReceiverVolume.xml). -->
<includes>
	<variable name="DenonHelp">
{help_var}
	</variable>
	<variable name="DenonConnectionText">
		<value condition="{ON}">[COLOR button_focus]{s(31915)}[/COLOR]$INFO[{P}(Denon.InputName), · ]</value>
		<value condition="{CONNECTED}">[COLOR button_focus]{s(31915)}[/COLOR] · {s(31967)}</value>
		<value condition="String.IsEmpty(Window(Home).Property(Denon.Host))">{s(31955)}</value>
		<value>[COLOR red]{s(31916)}[/COLOR]</value>
	</variable>
	<variable name="DenonStatusText">
		<value condition="{ON}">$INFO[{P}(Denon.Model)]$INFO[{P}(Denon.Format), · ]</value>
		<value condition="{CONNECTED}">$INFO[{P}(Denon.Model)] · {s(31967)}</value>
		<value>{s(31916)}</value>
	</variable>
	<variable name="DenonSignalText">
		<value condition="!String.IsEmpty({P}(Denon.Signal))">$INFO[{P}(Denon.Signal)]</value>
		<value>{s(31970)}</value>
	</variable>
	<variable name="DenonVolumeText">
		<value condition="String.IsEqual({P}(Denon.Mute),true)">$INFO[{P}(Denon.VolumeDisplay)]$INFO[{P}(Denon.Volume), (, dB)] · {s(31906)}</value>
		<value>$INFO[{P}(Denon.VolumeDisplay)]$INFO[{P}(Denon.Volume), (, dB)]</value>
	</variable>
	<variable name="DenonVolumeStep">
{steps}
	</variable>
	<variable name="DenonMaxVolume">
		<value>$INFO[Window(Home).Property(Denon.MaxVolume),, dB]</value>
	</variable>
</includes>
"""


if __name__ == "__main__":
    OUT.write_text(build())
    INCLUDES.write_text(build_includes())
    print(OUT, INCLUDES, sep="\n")
