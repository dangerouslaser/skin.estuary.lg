"""Generate the OSD panels: xml/Custom_1124_SonosPanel.xml (service.sonos),
xml/Custom_1125_DenonPanel.xml (service.denonavr) and xml/Custom_1126_LGTVPanel.xml
(service.webostv).

Laid out like the OSD's own settings dialogs (SettingsDialogLayout). They stay
open: every row shows the add-on's live Sonos.* / Denon.* properties, and the
buttons send commands to the running add-on with the NotifyAll builtin (no
script start, no dialog), so a toggle flips in place, a change from another
remote shows at once, and repeated volume presses add up. Left and Right on
the Volume row turn it down and up. Back closes the panel.

The LG TV panel's rows pick from a list (picture preset, motion, each picture
setting, sound output): a row opens just that list over the panel, and the
add-on updates the WebOS.* / WebOS.OSD.* values it shows when the pick is made
(and when the panel opens, for the values the TV doesn't push).

    python3 tools/gen_osd_panels.py
"""

from __future__ import annotations

from pathlib import Path

XML = Path(__file__).resolve().parent.parent / "xml"
P = "Window(Home).Property"
WIDTH, ROW, HEADER = 800, 70, 80


def s(n: int) -> str:
    return f"$LOCALIZE[{n}]"


def notify(addon: str, command: str) -> str:
    return f"NotifyAll({addon},{command})"


def open_page(window_id: int) -> tuple[str, ...]:
    """More settings: the add-on's settings page. The panel is a modal dialog, so
    it (and the OSD under it) closes first, or the page would open beneath it."""
    return ("<onclick>Dialog.Close(all,true)</onclick>", f"<onclick>ActivateWindow({window_id})</onclick>")


def button(cid: int, label: str, label2: str = "", onclick: str = "", visible: str = "",
           extra: tuple[str, ...] = ()) -> str:
    lines = [f'<control type="button" id="{cid}">',
             f'\t<include content="DialogSettingButton"><param name="width" value="{WIDTH}" /></include>',
             f"\t<label>{label}</label>"]
    if label2:
        lines.append(f"\t<label2>[B]{label2}[/B]</label2>")
    if onclick:
        lines.append(f"\t<onclick>{onclick}</onclick>")
    lines += [f"\t{e}" for e in extra]
    if visible:
        lines.append(f"\t<visible>{visible}</visible>")
    lines.append("</control>")
    return "\n".join("\t\t\t\t\t" + line for line in lines)


def radio(cid: int, label: str, selected: str, onclick: str, visible: str = "") -> str:
    lines = [f'<control type="radiobutton" id="{cid}">',
             f'\t<include content="DialogSettingButton"><param name="width" value="{WIDTH}" /></include>',
             f"\t<radioposx>{WIDTH - 110}</radioposx>",
             f"\t<label>{label}</label>", f"\t<selected>{selected}</selected>",
             f"\t<onclick>{onclick}</onclick>"]
    if visible:
        lines.append(f"\t<visible>{visible}</visible>")
    lines.append("</control>")
    return "\n".join("\t\t\t\t\t" + line for line in lines)


def panel(window_id: int, header: str, rows: list[str], comment: str, onload: str = "") -> str:
    height = len(rows) * ROW
    body = "\n".join(rows)
    load = f"\n\t<onload>{onload}</onload>" if onload else ""
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<!-- GENERATED by tools/gen_osd_panels.py. {comment} -->
<window type="dialog" id="{window_id}">
	<defaultcontrol always="true">9000</defaultcontrol>{load}
	<include>Animation_DialogPopupOpenClose</include>
	<controls>
		<control type="group">
			<centerleft>50%</centerleft>
			<centertop>50%</centertop>
			<width>{WIDTH}</width>
			<height>{HEADER + height}</height>
			<include content="DialogBackgroundCommons">
				<param name="width" value="{WIDTH}" />
				<param name="height" value="{HEADER}" />
				<param name="header_label" value="{header}" />
				<param name="header_id" value="1" />
			</include>
			<control type="group">
				<top>{HEADER}</top>
				<control type="grouplist" id="9000">
					<width>{WIDTH}</width>
					<height>{height}</height>
					<itemgap>0</itemgap>
					<onup>9000</onup>
					<ondown>9000</ondown>
					<orientation>vertical</orientation>
{body}
				</control>
			</control>
		</control>
	</controls>
</window>
"""


def sonos() -> str:
    addon = "service.sonos"

    def has(prop: str) -> str:
        return f"!String.IsEmpty({P}(Sonos.{prop}))"

    rows = [
        button(100, s(31957), "$VAR[SonosFormatText]"),
        button(101, s(31905), "$VAR[SonosVolumeText]",
               extra=(f"<onleft>{notify(addon, 'volume_down')}</onleft>",
                      f"<onright>{notify(addon, 'volume_up')}</onright>")),
        button(102, s(31987), onclick=notify(addon, "volume_up")),
        button(103, s(31988), onclick=notify(addon, "volume_down")),
        radio(104, s(31906), f"String.IsEqual({P}(Sonos.Mute),true)", notify(addon, "mute")),
        radio(105, s(31975), f"String.IsEqual({P}(Sonos.Night),true)", notify(addon, "night"), has("Night")),
        radio(106, s(31976), f"String.IsEqual({P}(Sonos.Speech),true)", notify(addon, "speech"), has("Speech")),
        button(107, s(31989), extra=open_page(1123)),
    ]
    return panel(1124, f"$INFO[{P}(Sonos.Room),$LOCALIZE[31971] · ]", rows,
                 "The OSD's Sonos panel (service.sonos): incoming\n     audio, volume, mute, night mode, "
                 "speech enhancement.")


def denon() -> str:
    addon = "service.denonavr"
    on = f"String.IsEqual({P}(Denon.Power),true)"
    rows = [
        button(100, s(31957), "$VAR[DenonSignalText]", visible=on),
        button(101, s(31958), f"$INFO[{P}(Denon.SoundMode)]", visible=on),
        button(102, s(31902), f"$INFO[{P}(Denon.InputName)]", visible=on),
        button(103, s(31905), "$VAR[DenonVolumeText]", visible=on,
               extra=(f"<onleft>{notify(addon, 'volume_down')}</onleft>",
                      f"<onright>{notify(addon, 'volume_up')}</onright>")),
        button(104, s(31987), onclick=notify(addon, "volume_up"), visible=on),
        button(105, s(31988), onclick=notify(addon, "volume_down"), visible=on),
        radio(106, s(31906), f"String.IsEqual({P}(Denon.Mute),true)", notify(addon, "mute"), on),
        radio(107, s(31918), on, notify(addon, "power")),
        button(108, s(31989), extra=open_page(1121)),
    ]
    return panel(1125, f"$INFO[{P}(Denon.Model),Denon ,]", rows,
                 "The OSD's Denon panel (service.denonavr): incoming\n     audio, how it plays, input, "
                 "volume, mute, power.")


def lgtv() -> str:
    addon = "service.webostv"

    def a(n: int) -> str:
        return f"$ADDON[{addon} {n}]"

    def ui(*args: str) -> str:
        return f"RunScript({addon},{','.join(('ui', *args))})"

    def osd(key: str) -> str:
        return f"$INFO[{P}(WebOS.OSD.{key})]"

    # OSD_ADJUSTMENTS in service.webostv's ui.py, with their labels: each shows
    # once the TV reports it for the picture mode in use.
    adjustments = (("backlight", 32500), ("hdrDynamicToneMapping", 32501), ("noiseReduction", 32502),
                   ("mpegNoiseReduction", 32503), ("smoothGradation", 32504), ("superResolution", 32505),
                   ("eyeComfortMode", 32506))
    rows = [
        button(100, a(32117), f"$INFO[{P}(WebOS.PicturePresetLabel)]", onclick=ui("picture_preset")),
        button(101, a(32430), osd("Motion"), onclick=ui("motion")),
        *(button(102 + i, a(label), osd(key), onclick=ui("adjust", key),
                 visible=f"!String.IsEmpty({P}(WebOS.OSD.{key}))")
          for i, (key, label) in enumerate(adjustments)),
        button(109, a(32102), f"$INFO[{P}(WebOS.SoundOutputLabel)]", onclick=ui("sound_output")),
        button(110, a(32432), extra=("<onclick>Dialog.Close(all,true)</onclick>",
                                    f"<onclick>RunScript({addon},screen,off)</onclick>")),
        button(111, s(31989), extra=open_page(1120)),
    ]
    return panel(1126, a(32431), rows,
                 "The OSD's LG TV panel (service.webostv): picture\n     preset, motion, picture settings, "
                 "sound output, screen off.", onload=ui("osd_values"))


if __name__ == "__main__":
    for name, text in (("Custom_1124_SonosPanel.xml", sonos()), ("Custom_1125_DenonPanel.xml", denon()),
                       ("Custom_1126_LGTVPanel.xml", lgtv())):
        (XML / name).write_text(text)
        print(XML / name)
