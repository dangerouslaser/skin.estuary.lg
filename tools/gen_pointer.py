"""Generate xml/Pointer.xml, the mouse pointer.

    python3 tools/gen_pointer.py

With the Remote Bridge, service.webostv saves the TV's own webOS pointer images
to its add-on data (and reloads the skin when they change: Kodi loads pointer
textures with the skin, and ignores $INFO textures here). Without them the
skin's webOS-style ones are the fallback (media/pointer_*.png,
tools/make_pointer.py). All are 256x256 with the hotspot in the middle (the TV's
pointer can point any way, in three sizes), so left/top put it on the pointer
position.

The current webOS pointer is animated too, and the add-on builds those as
anim_<look>.apng: while WebOS.PointerLook names one (the wheel scrolling: down,
up, downx/upx when it turns back, end as it rests; enter as the pointer appears,
exit as it goes) the pointer and focus pointer play it instead, and Kodi's click
pointer plays anim_press once WebOS.PointerAnimated is set (the add-on sets both
only when it has the animations). Kodi shows only the control whose id is the
pointer state, so these sit inside those groups; an animation restarts each time
it's shown.
"""

from __future__ import annotations

from pathlib import Path

XML = Path(__file__).resolve().parent.parent / "xml" / "Pointer.xml"
DATA = "special://profile/addon_data/service.webostv/pointer"
LOOK = "Window(Home).Property(WebOS.PointerLook)"
ANIMATED = "String.IsEqual(Window(Home).Property(WebOS.PointerAnimated),true)"
LOOKS = ("down", "up", "downx", "upx", "end", "enter", "exit")
# Kodi's pointer states: control id, description, the add-on's image, the fallback.
STATES = ((1, "Pointer", "point", "pointer_arrow.png"), (2, "Pointer Focus", "hover", "pointer_focus.png"),
          (3, "Pointer Drag", "drag", "pointer_arrow.png"), (4, "pointer_click", "hold", "pointer_click.png"))


def image(texture: str, visible: str = "", indent: int = 3) -> str:
    t = "\t" * indent
    lines = [f'{t}<control type="image">', f"{t}\t<left>-128</left>", f"{t}\t<top>-128</top>",
             f"{t}\t<width>256</width>", f"{t}\t<height>256</height>", f"{t}\t{texture}"]
    if visible:
        lines.append(f"{t}\t<visible>{visible}</visible>")
    lines.append(f"{t}</control>")
    return "\n".join(lines)


def state(cid: int, description: str, kind: str, fallback: str) -> str:
    still = f'<texture fallback="{fallback}">{DATA}/{kind}.png</texture>'
    if kind in ("point", "hover"):
        parts = [image(still, f"String.IsEmpty({LOOK})"),
                 *(image(f"<texture>{DATA}/anim_{look}.apng</texture>", f"String.IsEqual({LOOK},{look})")
                   for look in LOOKS)]
    elif kind == "hold":
        parts = [image(still, f"!{ANIMATED}"), image(f"<texture>{DATA}/anim_press.apng</texture>", ANIMATED)]
    else:
        parts = [image(still)]
    body = "\n".join(parts)
    return (f'\t\t<control type="group" id="{cid}">\n\t\t\t<description>{description}</description>\n'
            f"{body}\n\t\t</control>")


def pointer() -> str:
    states = "\n".join(state(*s) for s in STATES)
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<!-- GENERATED by tools/gen_pointer.py (how it works: there). Mouse pointer: the TV's own
     webOS pointer from service.webostv, and its animations. -->
<window>
	<controls>
{states}
	</controls>
</window>
"""


if __name__ == "__main__":
    XML.write_text(pointer())
    print(XML)
