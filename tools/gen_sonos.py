"""Generate xml/Custom_1123_Sonos.xml (the Sonos settings page) and
xml/Includes_Sonos.xml, laid out like the LG TV page (tools/gen_lgtv.py).
Values come from service.sonos's Sonos.* properties and its settings.

Includes_Sonos.xml also carries the variables the volume ring
(Custom_1122_ReceiverVolume.xml) uses to show whichever of the Denon and Sonos
add-ons changed volume.

    python3 tools/gen_sonos.py
"""

from __future__ import annotations

from pathlib import Path

from gen_lgtv import build_page

OUT = Path(__file__).resolve().parent.parent / "xml" / "Custom_1123_Sonos.xml"
INCLUDES = OUT.with_name("Includes_Sonos.xml")
ADDON = "service.sonos"
P = "Window(Home).Property"
CONNECTED = f"String.IsEqual({P}(Sonos.Connected),true)"
# The add-on publishes its settings as properties: $INFO splits Addon.SettingStr(id,setting) at the comma.
HOST = f"$INFO[{P}(Sonos.Host)]"


def s(n: int) -> str:
    return f"$LOCALIZE[{n}]"


def run(*args: str) -> str:
    return f"RunScript({ADDON},{','.join(args)})"


def has(prop: str) -> str:
    return f"!String.IsEmpty({P}(Sonos.{prop}))"


# Rows as in gen_lgtv.py: ("button", id, label, onclick, label2, enable, help),
# ("radio", id, label, selected, [(condition, onclick)], enable, help),
# ("header", id, label), ("note", id, label, visible).
CATEGORIES = [
    ("player", s(31986), [
        ("button", 100, s(31911), run("osd"), "$VAR[SonosStatusText]", CONNECTED, s(31980)),
        ("button", 101, s(31974), run("osd"), "$VAR[SonosSourceText]", CONNECTED, s(31980)),
        ("button", 102, s(31957), run("osd"), "$VAR[SonosFormatText]", CONNECTED, s(31981)),
        ("radio", 103, s(31975), f"String.IsEqual({P}(Sonos.Night),true)", [("", run("night", "toggle"))],
         f"{CONNECTED} + {has('Night')}", s(31982)),
        ("radio", 104, s(31976), f"String.IsEqual({P}(Sonos.Speech),true)", [("", run("speech", "toggle"))],
         f"{CONNECTED} + {has('Speech')}", s(31983)),
    ]),
    ("volume", s(31905), [
        ("button", 200, s(31905), run("osd"), "$VAR[SonosVolumeText]", CONNECTED, s(31980)),
        ("radio", 201, s(31906), f"String.IsEqual({P}(Sonos.Mute),true)", [("", run("mute", "toggle"))],
         CONNECTED, ""),
        ("button", 202, s(31959), run("setting", "volume_step"), "$VAR[SonosVolumeStep]", "", s(31984)),
        ("button", 203, s(31960), run("setting", "max_volume"), f"$INFO[{P}(Sonos.MaxVolume)]", "", s(31985)),
        ("header", 290, s(31961)),
        ("radio", 204, "$ADDON[service.webostv 32635]", "Addon.SettingBool(service.webostv,bridge_volume_receiver)",
         [("", "RunScript(service.webostv,setting,bridge_volume_receiver)")],
         "$EXP[setup_lg] + Addon.SettingBool(service.webostv,remote_bridge)", "$ADDON[service.webostv 32685]"),
    ]),
    ("connection", s(31910), [
        ("button", 300, s(31972), run("find_player"), HOST, "", s(31978)),
        ("button", 301, s(31973), run("setting", "host"), HOST, "", s(31979)),
        ("button", 302, s(31914), f"Addon.OpenSettings({ADDON})", "", "", ""),
    ]),
]


def build() -> str:
    return build_page(
        window_id=1123, category_prop="sonos_category", categories=CATEGORIES, help_var="SonosHelp",
        icon="icons/settings/sonos.png", model_label=f"$INFO[{P}(Sonos.Room)]",
        status_label="$VAR[SonosConnectionText]", breadcrumb="$LOCALIZE[5] / $LOCALIZE[31971]",
        comment="Sonos settings page (Settings > Sonos). Layout follows the LG TV\n"
                "     page; values come from service.sonos.",
        generator="tools/gen_sonos.py")


def build_includes() -> str:
    helps = [(r[1], r[-1]) for _c, _l, rows in CATEGORIES for r in rows if r[0] in ("button", "radio") and r[-1]]
    help_var = "\n".join(f'\t\t<value condition="Control.HasFocus({cid})">{text}</value>' for cid, text in helps)
    steps = "\n".join(
        f'\t\t<value condition="Integer.IsEqual(Addon.SettingInt({ADDON},volume_step),{i})">{label}</value>'
        for i, label in enumerate(("1", "2", "5")))
    sonos_ring = f"$EXP[setup_sonos] + String.IsEqual({P}(Sonos.VolumeShow),true)"
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<!-- GENERATED by tools/gen_sonos.py. Variables for Custom_1123_Sonos.xml, and the
     volume ring's (Custom_1122_ReceiverVolume.xml): Sonos when it changed volume,
     else the Denon receiver. -->
<includes>
	<variable name="SonosHelp">
{help_var}
	</variable>
	<variable name="SonosConnectionText">
		<value condition="{CONNECTED}">[COLOR button_focus]{s(31915)}[/COLOR]$INFO[{P}(Sonos.Model), · ]</value>
		<value condition="String.IsEmpty({P}(Sonos.Host))">{s(31972)}</value>
		<value>[COLOR red]{s(31916)}[/COLOR]</value>
	</variable>
	<variable name="SonosStatusText">
		<value condition="{CONNECTED}">$INFO[{P}(Sonos.Model)]$INFO[{P}(Sonos.Format), · ]</value>
		<value>{s(31916)}</value>
	</variable>
	<variable name="SonosSourceText">
		<value condition="String.IsEqual({P}(Sonos.TV),true)">TV</value>
		<value>{s(31977)}</value>
	</variable>
	<variable name="SonosFormatText">
		<value condition="{has('Format')}">$INFO[{P}(Sonos.Format)]</value>
		<value>{s(31970)}</value>
	</variable>
	<variable name="SonosVolumeText">
		<value condition="String.IsEqual({P}(Sonos.Mute),true)">$INFO[{P}(Sonos.Volume)] · {s(31906)}</value>
		<value>$INFO[{P}(Sonos.Volume)]</value>
	</variable>
	<variable name="SonosVolumeStep">
{steps}
	</variable>
	<expression name="ring_sonos">{sonos_ring}</expression>
	<expression name="ring_show">[{sonos_ring}] | [$EXP[setup_denon] + String.IsEqual({P}(Denon.VolumeShow),true)]</expression>
	<expression name="ring_mute">[$EXP[ring_sonos] + String.IsEqual({P}(Sonos.Mute),true)] | [!$EXP[ring_sonos] + String.IsEqual({P}(Denon.Mute),true)]</expression>
	<variable name="RingPercent">
		<value condition="$EXP[ring_sonos]">$INFO[{P}(Sonos.VolumePercent)]</value>
		<value>$INFO[{P}(Denon.VolumePercent)]</value>
	</variable>
	<variable name="RingNumber">
		<value condition="$EXP[ring_sonos]">$INFO[{P}(Sonos.Volume)]</value>
		<value>$INFO[{P}(Denon.VolumeDisplay)]</value>
	</variable>
</includes>
"""


if __name__ == "__main__":
    OUT.write_text(build())
    INCLUDES.write_text(build_includes())
    print(OUT, INCLUDES, sep="\n")
